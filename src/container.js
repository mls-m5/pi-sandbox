import fs from 'node:fs';
import path from 'node:path';
import { createHash, randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { assert, atomicWrite, directory, privateDir, run, within } from './util.js';

// Multi-architecture manifest digest; updates are intentional source changes.
export const BASE_IMAGE = 'docker.io/library/node:24.14.0-bookworm-slim@sha256:d8e448a56fc63242f70026718378bd4b00f8c82e78d20eefb199224a4d8e33d8';
export const PI_VERSION = '1.2.0';
export const CONTAINER_HOME = '/pis/home';
const COMMANDS = new Set(['install', 'remove', 'uninstall', 'update', 'list', 'config', 'auth', 'mcp']);
const SESSION_OPTIONS = new Set(['-c', '--continue', '-r', '--resume', '--session', '--session-id', '--fork', '--no-session']);

export function piCommand(args = [], fresh = false) {
  const beforeSeparator = args.slice(0, args.indexOf('--') === -1 ? args.length : args.indexOf('--'));
  const selectsSession = beforeSeparator.some(arg => SESSION_OPTIONS.has(arg.split('=')[0]));
  // Management subcommands do not accept the conversation continuation option.
  return ['pi', ...(!fresh && !selectsSession && !COMMANDS.has(args[0]) ? ['--continue'] : []), ...args];
}

export function interactiveOutput(command) {
  if (command[0] !== 'pi') return true;
  const args = command.slice(1);
  const end = args.indexOf('--');
  const options = end === -1 ? args : args.slice(0, end);
  return !options.some((arg, index) => ['-p', '--print', '--export', '--help', '-h', '--version', '-v', '--list-models'].includes(arg)
    || /^--mode=(json|rpc)$/.test(arg)
    || (arg === '--mode' && ['json', 'rpc'].includes(options[index + 1])));
}

export function containerfile(config) {
  const packages = [...new Set(['bash', 'ca-certificates', 'git', 'ripgrep', ...config.image.packages])];
  return `# Generated by pis. Edit project.json with pis --edit instead.\nFROM ${BASE_IMAGE}\nUSER root\nRUN apt-get update && apt-get install -y --no-install-recommends ${packages.map(pkg => `'${pkg}'`).join(' ')} && rm -rf /var/lib/apt/lists/*\nRUN npm install -g --ignore-scripts @earendil-works/pi-coding-agent@${PI_VERSION}\n${config.image.extraInstructions.join('\n')}\nUSER root\nRUN mkdir -p /pis/home && chmod 1777 /pis/home\nWORKDIR /pis/home\nUSER node\nENTRYPOINT ["pi"]\nCMD []\n`;
}

export function imagePlan(config) {
  const content = containerfile(config);
  const fingerprint = createHash('sha256').update(content).digest('hex').slice(0, 20);
  return { content, image: `localhost/pis-${config.id}:${fingerprint}`, fingerprint };
}

export function inspectPodman() {
  assert(process.platform === 'linux', 'pis supports Linux only.');
  assert(process.getuid?.() !== 0, 'Run pis as your normal user, not root or sudo.');
  const result = spawnSync('podman', ['info', '--format', 'json'], { encoding: 'utf8' });
  if (result.error) throw new Error(`Podman is unavailable: ${result.error.message}`);
  assert(result.status === 0, `Cannot query Podman: ${result.stderr.trim()}`);
  let info;
  try { info = JSON.parse(result.stdout); } catch { throw new Error('Podman returned invalid info JSON.'); }
  assert(info.host?.security?.rootless === true, 'pis requires rootless Podman.');
  assert(info.host.serviceIsRemote !== true, 'Remote Podman is unsupported; same-path mounts require local Podman.');
  return info;
}

export async function ensureImage(store, config, { rebuild = false } = {}) {
  const plan = imagePlan(config);
  const dir = store.projectDir(config.id);
  const context = path.join(dir, 'build');
  privateDir(context);
  assert(fs.readdirSync(context).every(file => file === 'Containerfile'), `Unexpected files in generated build context: ${context}. Move them elsewhere before building.`);
  atomicWrite(path.join(dir, 'Containerfile'), plan.content);
  atomicWrite(path.join(context, 'Containerfile'), plan.content);
  const exists = spawnSync('podman', ['image', 'exists', plan.image]);
  if (exists.error) throw exists.error;
  assert([0, 1].includes(exists.status), 'Cannot check whether the sandbox image exists.');
  if (rebuild || exists.status !== 0) {
    console.error(`pis: building ${plan.image}`);
    const code = await run('podman', ['build', '--http-proxy=false', ...(rebuild ? ['--no-cache'] : []), '--tag', plan.image, '--file', path.join(context, 'Containerfile'), context], { stdio: ['ignore', 2, 2] });
    assert(code === 0, `Image build failed (exit ${code}).`);
  }
  return plan;
}

export function launchArgs(store, config, command, { cwd, image, selinux = false, tty = Boolean(process.stdin.isTTY && process.stdout.isTTY && interactiveOutput(command)), uid = process.getuid(), gid = process.getgid(), name = `pis-${config.id}-${randomBytes(5).toString('hex')}` } = {}) {
  const workdir = within(config.root, cwd) ? cwd : config.root;
  const state = path.join(store.projectDir(config.id), 'state');
  const sharedLabel = selinux ? ',z' : '';
  const privateLabel = selinux ? ',Z' : '';
  const args = ['run', '--rm', '--init', '--name', name, '--interactive', ...(tty ? ['--tty'] : []),
    '--userns=keep-id', '--user', `${uid}:${gid}`, '--cap-drop=all', '--security-opt=no-new-privileges',
    '--http-proxy=false', '--workdir', workdir,
    '--env', `HOME=${CONTAINER_HOME}`, '--env', `PI_CODING_AGENT_DIR=${CONTAINER_HOME}/.pi/agent`,
    '--env', `PI_CODING_AGENT_SESSION_DIR=${CONTAINER_HOME}/.pi/agent/sessions`,
    '--env', 'PI_SKIP_VERSION_CHECK=1',
    '--volume', `${config.root}:${config.root}:rw${sharedLabel}`,
    '--volume', `${state}:${CONTAINER_HOME}:rw${privateLabel}`];
  for (const mount of config.mounts) args.push('--volume', `${mount.source}:${mount.source}:${mount.access === 'read-write' ? 'rw' : 'ro'}${sharedLabel}`);
  for (const variable of config.credentials.env) if (process.env[variable]) args.push('--env', variable);
  for (const variable of ['TERM', 'COLORTERM']) if (process.env[variable]) args.push('--env', variable);
  args.push('--entrypoint', '/usr/bin/env', image, ...command);
  return { args, name, workdir };
}

export async function launch(store, config, options) {
  return store.projectLock(config.id, async () => {
    // Re-read and validate after acquiring exclusivity (configuration may have changed).
    config = store.load(config.id);
    directory(config.root);
    const info = inspectPodman();
    const plan = await ensureImage(store, config, options);
    if (options.buildOnly) return 0;
    const command = options.mode === 'bash' ? ['bash', '-i'] : options.mode === 'exec' ? options.args : piCommand(options.args, options.fresh);
    if (options.mode === 'pi') {
      const missing = config.credentials.env.filter(variable => !process.env[variable]);
      if (missing.length) console.error(`pis: credentials not set: ${missing.join(', ')}. Set them on the host, adjust pis --edit, or use sandbox-local Pi login.`);
    }
    const state = path.join(store.projectDir(config.id), 'state');
    privateDir(state);
    const invocation = launchArgs(store, config, command, { cwd: options.cwd, image: plan.image, selinux: info.host.security.selinuxEnabled });
    try { return await run('podman', invocation.args); }
    finally {
      // Covers interrupted attached clients that leave their container running.
      spawnSync('podman', ['rm', '--force', '--time', '1', invocation.name], { stdio: 'ignore', timeout: 15_000 });
    }
  });
}
