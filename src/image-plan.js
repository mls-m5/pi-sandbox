import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { assert } from './util.js';
import { CLAUDE_VERSION } from './claude-code.js';
import { extensionManifest, IMAGE_AGENT_DIR, shellQuote } from './extensions.js';

// Multi-architecture manifest digest; updates are intentional source changes.
export const BASE_IMAGE =
  'docker.io/library/node:24.14.0-bookworm-slim@sha256:d8e448a56fc63242f70026718378bd4b00f8c82e78d20eefb199224a4d8e33d8';
export const PI_VERSION = '1.5.0';

export function containerfile(config, { piVersion = PI_VERSION, releaseLock } = {}) {
  assert(/^\d+\.\d+\.\d+$/.test(piVersion), 'Invalid Pi release version.');
  // A shared, content-addressed prefix: project apt lists/custom RUNs and small
  // frequently changing bootstrap/probe files must not invalidate npm installs.
  const common = ['bash', 'ca-certificates', 'git', 'ripgrep'];
  const declared = [...new Set(config.image.packages)];
  // Reuse the relatively large default development tools too, but ONLY when
  // explicitly declared. Keep version-qualified overrides in the final solver.
  const sharedTools = ['build-essential', 'python3'].filter(
    (pkg) => declared.includes(pkg) && !declared.some((entry) => entry.startsWith(`${pkg}=`)),
  );
  const packages = declared.filter((pkg) => !common.includes(pkg) && !sharedTools.includes(pkg));
  const apt = (list) =>
    `RUN apt-get update && apt-get install -y --no-install-recommends ${list.some((pkg) => pkg.includes('=')) ? '--allow-downgrades ' : ''}${list.map(shellQuote).join(' ')} && rm -rf /var/lib/apt/lists/* /var/cache/apt/archives/*`;
  const cleanNpm = 'rm -rf /tmp/pis-npm-cache /root/.npm';
  const claudeInstall =
    config.agent === 'claude'
      ? `RUN npm_config_cache=/tmp/pis-npm-cache npm install -g --ignore-scripts @anthropic-ai/claude-code@${CLAUDE_VERSION} && node /usr/local/lib/node_modules/@anthropic-ai/claude-code/install.cjs && claude --version && ${cleanNpm}\n`
      : '';
  const piInstall = releaseLock
    ? `COPY update-lock.json verified-install.mjs /opt/pis/\nRUN mkdir -p ${IMAGE_AGENT_DIR} && node /opt/pis/verified-install.mjs && chmod -R a+rX ${IMAGE_AGENT_DIR} && ${cleanNpm}`
    : `RUN npm_config_cache=/tmp/pis-npm-cache npm install -g --ignore-scripts @earendil-works/pi-coding-agent@${piVersion} && ${cleanNpm}`;
  const entries = releaseLock ? [] : extensionManifest(config.extensions);
  const installs = releaseLock
    ? ''
    : `RUN mkdir -p ${IMAGE_AGENT_DIR}${entries.map((entry) => ` && PI_CODING_AGENT_DIR=${IMAGE_AGENT_DIR} PI_OFFLINE=1 NPM_CONFIG_CACHE=/tmp/pis-npm-cache NPM_CONFIG_IGNORE_SCRIPTS=true pi install ${shellQuote(entry.source)}`).join('')} && chmod -R a+rX ${IMAGE_AGENT_DIR} && ${cleanNpm}\n`;
  const runtimeFiles = [
    'extensions.json',
    'image-entry.mjs',
    'fetch-bridge.mjs',
    'request-apt.mjs',
    'claude-host-mcp.mjs',
    'codex-auto.mjs',
    'update-probe.mjs',
    'probe-policy.json',
    ...(releaseLock ? ['managed-release.json', 'update-lock.json', 'verified-install.mjs'] : []),
    'pi-launcher',
  ];
  return `# Generated by pis. Edit project.json with pis --edit instead.\nFROM ${BASE_IMAGE}\nUSER root\n${apt(common)}\n${piInstall}\n${claudeInstall}${installs}# Project customization starts here; runtime layers above are shared.\n${sharedTools.length ? `${apt(sharedTools)}\n` : ''}${packages.length ? `${apt(packages)}\n` : ''}${config.image.extraInstructions.join('\n')}\nUSER root\nCOPY ${runtimeFiles.join(' ')} /opt/pis/\n${releaseLock ? 'COPY probe-lib /opt/pis/probe-lib\n' : ''}RUN mv /usr/local/bin/pi /usr/local/bin/pis-pi-real && cp /opt/pis/pi-launcher /usr/local/bin/pi && chmod 755 /usr/local/bin/pi && chmod a+r ${runtimeFiles.map((file) => `/opt/pis/${file}`).join(' ')}${releaseLock ? ' && chmod -R a+rX /opt/pis/probe-lib' : ''} && mkdir -p /pis/home && chmod 1777 /pis/home\nWORKDIR /pis/home\nUSER node\nENTRYPOINT ["/usr/local/bin/node", "/opt/pis/image-entry.mjs"]\nCMD ["pi"]\n`;
}

export function imagePlan(config, { piVersion = PI_VERSION, releaseLock, releaseId } = {}) {
  assert(
    !releaseLock || (typeof releaseId === 'string' && /^[a-f0-9]{32}$/.test(releaseId)),
    'Managed images require a unique release build identity.',
  );
  const content = containerfile(config, { piVersion, releaseLock });
  const files = {
    Containerfile: content,
    'extensions.json': `${JSON.stringify(extensionManifest(config.extensions), null, 2)}\n`,
    'image-entry.mjs': fs.readFileSync(
      new URL('./runtime/image-entry.mjs', import.meta.url),
      'utf8',
    ),
    'fetch-bridge.mjs': fs.readFileSync(
      new URL('./runtime/fetch-bridge.mjs', import.meta.url),
      'utf8',
    ),
    'request-apt.mjs': fs.readFileSync(
      new URL('./runtime/request-apt.mjs', import.meta.url),
      'utf8',
    ),
    'claude-host-mcp.mjs': fs.readFileSync(
      new URL('./runtime/claude-host-mcp.mjs', import.meta.url),
      'utf8',
    ),
    'codex-auto.mjs': fs.readFileSync(new URL('./runtime/codex-auto.mjs', import.meta.url), 'utf8'),
    'pi-launcher': fs.readFileSync(new URL('./runtime/pi-launcher', import.meta.url), 'utf8'),
    'update-probe.mjs': fs.readFileSync(
      new URL('./runtime/update-probe.mjs', import.meta.url),
      'utf8',
    ),
    'probe-policy.json': `${JSON.stringify({ piVersion, extensions: config.extensions })}\n`,
    ...(releaseLock
      ? {
          'update-lock.json': `${JSON.stringify(releaseLock)}\n`,
          'managed-release.json': `${JSON.stringify({ id: releaseId })}\n`,
          'verified-install.mjs': fs.readFileSync(
            new URL('./runtime/verified-install.mjs', import.meta.url),
            'utf8',
          ),
          'probe-lib/package.json': '{"type":"module"}\n',
          ...Object.fromEntries(
            ['proxy.js', 'codex-auth.js', 'codex-usage.js', 'util.js'].map((name) => [
              `probe-lib/${name}`,
              fs.readFileSync(new URL(`./${name}`, import.meta.url), 'utf8'),
            ]),
          ),
        }
      : {}),
  };
  const fingerprint = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 20);
  return {
    content,
    files,
    image: `localhost/pis-${config.id}:${fingerprint}`,
    fingerprint,
    piVersion,
  };
}
